// Starting points for the /cmux page: twelve colour schemes that are genuinely popular
// in the developer community, and five made for this site.
//
// The two kinds are labelled differently on the page on purpose, because they are
// different claims:
//
//   kind: 'community'  — a real, widely-used scheme with an author and a following.
//     `theme` is the EXACT filename of a theme Ghostty already ships (463 of them
//     live in cmux.app/Contents/Resources/ghostty/themes), so the install writes one
//     `theme = X` line and the user's own installed theme file does the rendering.
//     `credit` names whoever made it. `evidence` is why we call it popular.
//
//   kind: 'example'    — made here. There is no theme file to point at, so `scheme`
//     carries the colours literally: a background, a foreground and all sixteen ANSI
//     slots, written straight into the Ghostty config. That makes it a real colour
//     scheme rather than a rename of somebody else's.
//
// `pal` is the same scheme mapped onto the 14 keys the rest of the site uses, and it
// drives two things: the AFTER preview, and the cmux chrome (pane borders, sidebar
// tint, workspace selection) so the window matches the terminal inside it.
//
// The community palettes are NOT hand-typed. They are generated by
// `node tools/extract-ghostty-themes.js` reading the actual theme files out of the
// installed cmux bundle — 19 hex values each, where one wrong digit would be
// invisible in review and would make the preview lie about what gets installed. Rerun
// that script to refresh them; do not edit the numbers here by hand.
//
// A payload only ever carries a preset ID, never a preset's contents, so a share link
// can name one of these looks but cannot invent a new one — there is no path from a
// link to arbitrary hex in someone's config file through this table.

