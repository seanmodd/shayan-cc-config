/** Every preset id, in page order. */
const PRESET_IDS = CMUX_PRESETS.map(p => p.id);

function isPresetId(v) {
  return typeof v === 'string' && v !== '' && PRESET_IDS.indexOf(v) >= 0;
}

function presetById(id) {
  if (!isPresetId(id)) return null;
  return CMUX_PRESETS.find(p => p.id === id) || null;
}

/**
 * The 14-key palette for a preset: read from the bundled theme file for a community
 * preset, carried inline for one of ours. Returns null for an unknown id so callers
 * fall back to the Claude Code palette rather than to a wrong one.
 */
function presetPalette(id) {
  const p = presetById(id);
  if (!p) return null;
  if (p.pal) return p.pal;
  if (p.theme && Object.prototype.hasOwnProperty.call(COMMUNITY_PAL, p.theme)) {
    return COMMUNITY_PAL[p.theme];
  }
  return null;
}

/** What the page needs to render the picker and preview, without the server internals. */
function presetsForClient() {
  return CMUX_PRESETS.map(p => ({
    id: p.id,
    name: p.name,
    kind: p.kind,
    credit: p.credit || '',
    blurb: p.blurb || '',
    evidence: p.evidence || '',
    theme: p.theme || '',
    pal: presetPalette(p.id),
    cm: p.cm || {},
  }));
}

