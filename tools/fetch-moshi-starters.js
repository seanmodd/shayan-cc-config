// Vendor a handful of starter themes for /moshi from the OFFICIAL gallery —
// getmoshi.app serves every theme as ready JSON at /themes/<slug>.json, and the
// import mechanism on the page is byte-compatible with these files.
//
// Committed output: api/_moshi_starters.js. Rerun only to refresh the set:
//   node tools/fetch-moshi-starters.js
const https = require('https');
const fs = require('fs');
const path = require('path');

const SLUGS = [
  'dracula', 'nord', 'catppuccin-mocha', 'catppuccin-latte', 'tokyonight',
  'gruvbox-dark', 'solarized-dark-patched', 'iterm2-solarized-light', 'rose-pine', 'github-dark',
];

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'user-agent': 'shayan-cc-config-tools' } }, res => {
      if (res.statusCode !== 200) { reject(new Error(url + ' -> ' + res.statusCode)); return; }
      let b = '';
      res.on('data', c => { b += c; });
      res.on('end', () => { try { resolve(JSON.parse(b)); } catch (e) { reject(e); } });
    }).on('error', reject);
  });
}

async function main() {
  const out = {};
  for (const slug of SLUGS) {
    try {
      const t = await fetchJson('https://getmoshi.app/themes/' + slug + '.json');
      if (t.v !== 1 || !t.colors || !t.colors.background) throw new Error('unexpected shape');
      out[slug] = t;
      console.log('  ✓', slug, t.name, t.mode);
    } catch (e) {
      console.error('  ✗', slug, e.message);
    }
  }
  const body = Object.entries(out)
    .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`).join('\n');
  fs.writeFileSync(path.join(__dirname, '..', 'api', '_moshi_starters.js'),
    `// GENERATED by tools/fetch-moshi-starters.js — do not edit by hand.
//
// Starter themes for /moshi, vendored verbatim from the official gallery
// (getmoshi.app/themes/<slug>.json). Each is the exact JSON the app imports.

const MOSHI_STARTERS = {
${body}
};

module.exports = { MOSHI_STARTERS };
`);
  console.log('wrote api/_moshi_starters.js with ' + Object.keys(out).length + ' themes');
}

if (require.main === module) main();
